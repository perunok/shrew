/// Renders a key as a vim double-quoted string fragment.
fn vim_key(k: &KeyPress) -> String {
    let m = k.mods;
    let name = match k.key {
        Key::Char(c) if !m.ctrl && !m.alt => {
            return match c {
                '"' => "\\\"".into(),
                '\\' => "\\\\".into(),
                c => c.to_string(),
            };
        }
        Key::Char(c) => c.to_string(),
        Key::Enter => "CR".into(),
        Key::Esc => "Esc".into(),
        Key::Backspace => "BS".into(),
        Key::Delete => "Del".into(),
        Key::Tab => "Tab".into(),
        Key::Left => "Left".into(),
        Key::Right => "Right".into(),
        Key::Up => "Up".into(),
        Key::Down => "Down".into(),
        Key::Home => "Home".into(),
        Key::End => "End".into(),
        Key::PageUp => "PageUp".into(),
        Key::PageDown => "PageDown".into(),
        Key::Insert => "Insert".into(),
        Key::F(n) => format!("F{n}"),
    };
    let mut s = String::from("\\<");
    if m.ctrl {
        s.push_str("C-");
    }
    if m.alt {
        s.push_str("M-");
    }
    if m.shift {
        s.push_str("S-");
    }
    s.push_str(&name);
    s.push('>');
    s
}

fn split_start(start: &str) -> (String, usize) {
    let b = start.find('|').expect("start text needs a | cursor");
    (start.replacen('|', "", 1), start[..b].chars().count())
}

/// `vim` if installed, else `nvim` (the bool).
fn vim_bin() -> Option<(PathBuf, bool)> {
    let path = std::env::var_os("PATH")?;
    let find = |name: &str| std::env::split_paths(&path).map(|d| d.join(name)).find(|p| p.is_file());
    find("vim").map(|p| (p, false)).or_else(|| find("nvim").map(|p| (p, true)))
}

/// Runs every case in one vim process. Returns (text, cursor char index) per case.
fn run_vim((vim, neovim): &(PathBuf, bool), cases: &[(&str, &str)]) -> Vec<(String, usize)> {
    let dir = std::env::temp_dir().join(format!("shrew-vim-diff-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let out_path = dir.join("out.txt");
    let mut script = String::from(
        "scriptencoding utf-8\nset nocompatible encoding=utf-8 sw=4 ts=4 sts=0 et autoindent so=4 nrformats=bin,hex\n\
         set noswapfile shortmess+=A ignorecase smartcase\n\
         set startofline nojoinspaces nrformats=bin,hex\n\
         silent! nunmap Y\nlet g:out = []\n\
         function! Run(lines, l, c, keys) abort\n\
           enew!\n  set ul=-1\n  call setline(1, a:lines)\n  set ul=1000\n\
           for r in split('abcdefghijklmnopqrstuvwxyz0123456789\"-', '\\zs')\n    call setreg(r, [])\n  endfor\n\
           delmarks!\n  call cursor(a:l, a:c)\n\
           try\n    call feedkeys(a:keys, 'xt')\n  catch\n  endtry\n\
           if mode() !=# 'n'\n    call feedkeys(\"\\<Esc>\\<Esc>\", 'xt')\n  endif\n\
           let off = line2byte(line('.')) + col('.') - 2\n\
           call add(g:out, \"\\x01@@ \" . off)\n  call extend(g:out, getline(1, '$'))\n\
         endfunction\n",
    );
    for (start, keys) in cases {
        let (text, pos) = split_start(start);
        let lines: Vec<String> = text.split('\n').map(|l| format!("'{}'", l.replace('\'', "''"))).collect();
        let before: String = text.chars().take(pos).collect();
        let line = before.matches('\n').count() + 1;
        let col = before.len() - before.rfind('\n').map_or(0, |i| i + 1) + 1;
        let feed: String = KeyPress::parse_seq(keys).iter().map(vim_key).collect();
        writeln!(script, "call Run([{}], {line}, {col}, \"{feed}\")", lines.join(", ")).unwrap();
    }
    writeln!(script, "call writefile(g:out, '{}')\nqa!", out_path.display()).unwrap();
    let script_path = dir.join("cases.vim");
    std::fs::write(&script_path, script).unwrap();
    let args: &[&str] = if *neovim {
        &["--headless", "--clean", "-n", "-i", "NONE", "-S"]
    } else {
        &["--clean", "-N", "-n", "-i", "NONE", "--not-a-term", "-S"]
    };
    let status = Command::new(vim)
        .args(args)
        .arg(&script_path)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .expect("vim runs");
    assert!(status.success(), "vim failed");
    let out = std::fs::read_to_string(&out_path).expect("vim wrote results");
    let _ = std::fs::remove_dir_all(&dir);
    let mut res = Vec::new();
    for rec in out.split("\x01@@ ").skip(1) {
        let mut lines = rec.split('\n');
        let off: isize = lines.next().unwrap().trim().parse().unwrap();
        let mut body: Vec<&str> = lines.collect();
        if body.last() == Some(&"") {
            body.pop(); // writefile's final newline
        }
        let text = body.join("\n");
        let off = off.max(0) as usize;
        let pos = text.char_indices().take_while(|(b, _)| *b < off).count();
        res.push((text, pos));
    }
    assert_eq!(res.len(), cases.len(), "vim produced a result per case");
    res
}

fn run_shrew(start: &str, keys: &str) -> (String, usize) {
    let (text, pos) = split_start(start);
    let mut e = Editor::new();
    e.install_document(Document::from_str(&text));
    e.set_feature(Feature::AutoPairs, false); // vim has none
    // vim cannot start on a line break
    let pos = shrew_core::text::clamp_normal(&e.buf().doc.rope, pos);
    e.buf_mut().sel = shrew_core::Selection::point(pos);
    e.buf_mut().view.rows = ROWS;
    for k in KeyPress::parse_seq(keys) {
        e.handle_key(k);
    }
    if e.mode != Mode::Normal {
        e.handle_key(KeyPress::plain(Key::Esc));
        e.handle_key(KeyPress::plain(Key::Esc));
    }
    (e.buf().doc.rope.to_string(), e.buf().sel.primary().head)
}

fn show(text: &str, pos: usize) -> String {
    let mut s = text.to_string();
    let b = s.char_indices().nth(pos).map_or(s.len(), |(b, _)| b);
    s.insert(b, '|');
    s.replace('\n', "⏎")
}

#[test]
fn matches_vim() {
    let Some(vim) = vim_bin() else {
        eprintln!("vim not found: skipping differential tests");
        return;
    };
    let expected = run_vim(&vim, CASES);
    let mut failures = Vec::new();
    for ((start, keys), (vt, vp)) in CASES.iter().zip(expected) {
        let got = std::panic::catch_unwind(|| run_shrew(start, keys));
        let ok = matches!(&got, Ok((t, p)) if *t == vt && *p == vp);
        if !ok {
            let got = match got {
                Ok((t, p)) => show(&t, p),
                Err(_) => "PANIC".into(),
            };
            let (st, sp) = split_start(start);
            failures.push(format!("{:<28} {:<22} vim: {:<28} shrew: {}", show(&st, sp), keys, show(&vt, vp), got));
        }
    }
    if !failures.is_empty() {
        let mut msg = format!("{} of {} cases differ from vim:\n", failures.len(), CASES.len());
        for f in &failures {
            msg.push_str(f);
            msg.push('\n');
        }
        panic!("{msg}");
    }
}
